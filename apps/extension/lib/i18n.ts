export type UiKey = keyof typeof STRINGS["zh-CN"];
export function t(language: HomepageLanguage,key: UiKey): string {return STRINGS[normalizeHomepageLanguage(language)][key];}
export function formatUi(language:HomepageLanguage,key:UiKey,args:Record<string,string|number>):string{
 return t(language,key).replace(/\{(\w+)\}/g,(full,k)=>String(args[k]??full));
}
export function describeBuildError(language:HomepageLanguage,message:string):string{
 const raw = (message||"").trim();
 if(/API key|API 密钥/.test(raw) && !/^Model API HTTP/.test(raw)) return t(language,"errorApiKey");
 if(/Model request failed|Failed to fetch|NetworkError|CORS/i.test(raw))return t(language,"errorConnection");
 const match=raw.match(/(?:Model API )?HTTP\s+(\d{3})/i);
 if(match)return formatUi(language,"errorHttp",{status:match[1]});
 if(/returned no text|no valid content/i.test(raw))return t(language,"errorNoContent");
 if(/Build cancelled|aborted|AbortError/i.test(raw))return t(language,"errorCancelled");
 if(/Invalid generated|Missing default|Homepage must import|Generated code|forbidden|prohibited|unverified source|no homepage/i.test(raw))return t(language,"errorInvalidOutput");
 return t(language,"errorGeneric")+raw.slice(0,180);
}
